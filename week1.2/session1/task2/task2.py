"""
in this task features are used suchas;
sort() - sorts the list aphabetically 
reverse() - reverse the list
clear() - removes all items within the list
"""
fruit = ["cherry", "strawberry", "melon", "grape", "apple"]

# Sort list
fruit.sort()
print(fruit)

# Reverse order of list items
fruit.reverse()
print(fruit)

# Remove all items
fruit.clear()
print(fruit)